-- Телефон обязателен по требованию, но объявить колонку NOT NULL нельзя:
-- пользователи, вошедшие через внешнего провайдера, создаются без телефона.
-- Требовать его в момент внешнего входа значит спрашивать номер до того,
-- как человек вообще решил остаться в системе.
--
-- Поэтому обязательность выражена условием: у того, кто регистрировался
-- с паролем, телефон должен быть. Внешний пользователь дозаполняет профиль
-- сам, и до тех пор его профиль считается неполным.
--
-- Ограничение добавляется как NOT VALID: существующие строки не проверяются,
-- иначе миграция упала бы на данных, накопленных до появления профиля,
-- и сервис не поднялся бы вовсе. Новые и изменяемые строки проверяются
-- сразу же.
--
-- Когда старые записи дозаполнены, ужесточение завершается вручную:
--   SELECT count(*) FROM users WHERE password_set AND phone IS NULL;
--   ALTER TABLE users VALIDATE CONSTRAINT users_phone_required;
--
-- Если когда-нибудь появится смена пароля, она обязана требовать телефон:
-- иначе внешний пользователь задаст пароль и нарушит это ограничение.
ALTER TABLE users
    ADD CONSTRAINT users_phone_required
        CHECK (NOT password_set OR phone IS NOT NULL) NOT VALID;
